/**
 * Deterministically returns the Verse of the Day for a given calendar date.
 * Uses local calendar date string (YYYY-MM-DD) so that Home screen and Notification
 * are GUARANTEED to present the exact same verse.
 */
export function getDeterministicDailyVerse(dateInput?: string | Date): DailyVerse {
  let targetDate: Date;
  if (!dateInput) {
    targetDate = new Date();
  } else if (typeof dateInput === 'string') {
    // Parse YYYY-MM-DD in local time
    const parts = dateInput.split('-').map(Number);
    if (parts.length === 3) {
      targetDate = new Date(parts[0], parts[1] - 1, parts[2]);
    } else {
      targetDate = new Date(dateInput);
    }
  } else {
    targetDate = dateInput;
  }

  const year = targetDate.getFullYear();
  const month = targetDate.getMonth();
  const day = targetDate.getDate();

  // Calculate day of the year
  const startOfYear = new Date(year, 0, 1);
  const diffTime = targetDate.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diffTime / (1000 * 60 * 60 * 24)) + 1;

  // Use (year * 365 + dayOfYear) to cycle through the library
  const seed = (year * 365 + dayOfYear);
  const index = Math.abs(seed) % COMPREHENSIVE_DAILY_VERSES.length;

  const dateStr = `${year}-${String(month + 1).padStart(2, '0')}-${String(day).padStart(2, '0')}`;

  const baseVerse = COMPREHENSIVE_DAILY_VERSES[index];
  return {
    ...baseVerse,
    date: dateStr,
  };
}
