export function searchHymns(query: string, category?: string): SongHymn[] {
  let list = PUBLIC_DOMAIN_HYMNS;
  if (category && category !== 'All') {
    list = list.filter(h => h.category.toLowerCase() === category.toLowerCase());
  }
  if (!query || query.trim() === '') return list;
  const q = query.toLowerCase().trim();
  return list.filter(
    h =>
      h.title.toLowerCase().includes(q) ||
      (h.author && h.author.toLowerCase().includes(q)) ||
      h.lyrics.toLowerCase().includes(q)
  );
}
